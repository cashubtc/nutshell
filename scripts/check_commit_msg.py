#!/usr/bin/env python3
"""Validate a commit message subject against Conventional Commits.

Enforces the "Commit messages" section of AGENTS.md as a `commit-msg`
pre-commit hook (see .pre-commit-config.yaml). Subjects generated by git,
GitHub, and `git rebase --autosquash` (merge commits, reverts, and
`fixup!`/`squash!`) are allowed through.
"""

from __future__ import annotations

import re
import sys

# Keep in sync with the "Commit messages" section of AGENTS.md.
TYPES = (
    "feat",
    "fix",
    "docs",
    "style",
    "refactor",
    "perf",
    "test",
    "build",
    "ci",
    "chore",
    "revert",
)

# <type>(<scope>)!: <description>
CONVENTIONAL_RE = re.compile(rf"^({'|'.join(TYPES)})(\([^)\n]+\))?!?: .+")

# Subjects created by git, GitHub, and autosquash are always allowed.
ALLOWED_PREFIXES = ("Merge ", 'Revert "', "fixup! ", "squash! ")


def is_valid(subject: str) -> bool:
    """Return True if a commit subject follows the conventions."""
    if subject.startswith(ALLOWED_PREFIXES):
        return True
    return CONVENTIONAL_RE.match(subject) is not None


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"usage: {argv[0]} <commit-msg-file>", file=sys.stderr)
        return 2

    with open(argv[1], encoding="utf-8") as f:
        subject = f.readline().strip()

    if is_valid(subject):
        return 0

    print(
        f"invalid commit subject: {subject!r}\n"
        "\n"
        "Commit messages must follow Conventional Commits "
        "(see the 'Commit messages' section of AGENTS.md):\n"
        "\n"
        "    <type>(<scope>)!: <description>\n"
        "\n"
        f"with <type> one of: {', '.join(TYPES)}.\n"
        "Merge, revert, fixup!, and squash! subjects are also allowed.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
